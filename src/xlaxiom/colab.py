"""Interactive Google Colab notebook generation and Colab surface integration.

Generates self-contained, one-click interactive reproduction notebooks for
Google Colab with automatic hardware acceleration detection (TPU, GPU, CPU),
embedded workload cases, and rich visual diagnostics.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .storage import CaseArtifact, RelationalArtifact, atomic_write_text

COLAB_BADGE_URL = "https://colab.research.google.com/assets/colab-badge.svg"
COLAB_BASE_URL = "https://colab.research.google.com/github"


def colab_badge_markdown(repo: str, path_in_repo: str) -> str:
    """Generate official Google Colab Markdown badge targeting a repository path."""
    clean_path = path_in_repo.lstrip("/")
    target_url = f"{COLAB_BASE_URL}/{repo}/blob/main/{clean_path}"
    return f"[![Open In Colab]({COLAB_BADGE_URL})]({target_url})"


def generate_colab_notebook(
    artifact_or_data: CaseArtifact | RelationalArtifact | dict[str, Any],
    *,
    title: str = "XLAxiom Investigation Case",
    accelerator: str = "TPU",
) -> dict[str, Any]:
    """Generate a standard Jupyter v4 notebook dictionary optimized for Google Colab."""
    if isinstance(artifact_or_data, CaseArtifact):
        case_dict = artifact_or_data.to_dict()
        is_relational = False
    elif isinstance(artifact_or_data, RelationalArtifact):
        case_dict = artifact_or_data.to_dict()
        is_relational = True
    elif "relational_case_version" in artifact_or_data:
        case_dict = dict(artifact_or_data)
        is_relational = True
    else:
        case_dict = dict(artifact_or_data)
        is_relational = False

    case_json_str = json.dumps(case_dict, indent=2, sort_keys=True)
    provenance = case_dict.get("provenance", "generated")
    digest = case_dict.get("sha256", "N/A")

    cells = [
        {
            "cell_type": "markdown",
            "metadata": {},
            "source": [
                f"# {title}\n",
                "\n",
                f"**Artifact SHA-256**: `{digest}`  \n",
                f"**Target Accelerator**: `{accelerator}`  \n",
                f"**Provenance**: `{provenance}`  \n",
                "\n",
                "> This interactive Google Colab notebook was generated by **XLAxiom**, ",
                "the compiler verification and forensic evidence engine for JAX and OpenXLA.",
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 1. Environment & Accelerator Setup\n",
                "!pip install -q xlaxiom\n",
                "import jax\n",
                "import jax.numpy as jnp\n",
                "import numpy as np\n",
                "print('Active JAX Version:', jax.__version__)\n",
                "print('Discovered Devices:', jax.devices())\n",
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 2. Load Checksummed XLAxiom Case Artifact\n",
                "import json\n",
                f"raw_case_json = '''{case_json_str}'''\n",
                "case_data = json.loads(raw_case_json)\n",
                (
                    "from xlaxiom.storage import RelationalArtifact\n"
                    "artifact = RelationalArtifact.from_dict(case_data)\n"
                    if is_relational
                    else "from xlaxiom.storage import CaseArtifact\n"
                    "artifact = CaseArtifact.from_dict(case_data)\n"
                ),
                "print('Artifact loaded and checksum verified successfully.')\n",
                "artifact",
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 3. Execute Independent Differential Comparison\n",
                (
                    "from xlaxiom.relational import run_relational_comparison\n"
                    "result = run_relational_comparison(artifact)\n"
                    "print('Relational Verdict:', result.classification)\n"
                    if is_relational
                    else "from xlaxiom.pipeline import run_comparison\n"
                    "result = run_comparison(\n"
                    "    artifact.workload, artifact.comparison_mode, artifact.fault\n"
                    ")\n"
                    "print('Differential Verdict:', result.classification)\n"
                ),
                "result",
            ],
        },
    ]

    colab_metadata: dict[str, Any] = {
        "accelerator": accelerator,
        "colab": {
            "provenance": [],
            "toc_visible": True,
        },
        "kernelspec": {
            "display_name": "Python 3",
            "name": "python3",
        },
        "language_info": {
            "name": "python",
        },
    }

    return {
        "cells": cells,
        "metadata": colab_metadata,
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def save_colab_notebook(notebook: dict[str, Any], path: str | Path) -> Path:
    """Serialize and atomically write a Colab notebook JSON to disk."""
    content = json.dumps(notebook, indent=2, sort_keys=True) + "\n"
    return atomic_write_text(path, content)
