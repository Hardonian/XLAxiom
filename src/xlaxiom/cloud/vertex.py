"""Vertex AI Custom Job configuration and Kubeflow Pipelines (KFP) integration.

Enables automated execution of compiler differential campaigns and bisection runs
as managed Vertex AI workloads on Google Cloud.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class VertexJobSpec:
    display_name: str
    container_image_uri: str
    accelerator_type: str
    accelerator_count: int
    machine_type: str
    command: tuple[str, ...]
    output_gcs_uri: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "displayName": self.display_name,
            "jobSpec": {
                "workerPoolSpecs": [
                    {
                        "machineSpec": {
                            "machineType": self.machine_type,
                            "acceleratorType": self.accelerator_type,
                            "acceleratorCount": self.accelerator_count,
                        },
                        "replicaCount": 1,
                        "containerSpec": {
                            "imageUri": self.container_image_uri,
                            "command": list(self.command),
                            "env": [
                                {"name": "XLAXIOM_GCS_OUTPUT", "value": self.output_gcs_uri},
                            ],
                        },
                    }
                ],
                "baseOutputDirectory": {
                    "outputUriPrefix": self.output_gcs_uri,
                },
            },
        }


def create_vertex_job_spec(
    display_name: str = "xlaxiom-compiler-audit",
    accelerator: str = "TPU_V5E",
    accelerator_count: int = 4,
    container_image: str = "us-docker.pkg.dev/google-cloud/xlaxiom/runner:latest",
    command: tuple[str, ...] = (
        "xlaxiom",
        "property",
        "campaign",
        "--backend",
        "jax-tpu-jit",
        "--cases",
        "50",
    ),
    output_gcs_uri: str = "gs://xlaxiom-evidence-bucket/runs",
) -> VertexJobSpec:
    """Construct a production-ready Vertex AI Custom Job specification."""
    machine_type = "ct5lp-hightpu-4t" if "V5E" in accelerator else "n1-standard-8"
    return VertexJobSpec(
        display_name=display_name,
        container_image_uri=container_image,
        accelerator_type=accelerator,
        accelerator_count=accelerator_count,
        machine_type=machine_type,
        command=command,
        output_gcs_uri=output_gcs_uri,
    )


def generate_kfp_component_yaml() -> str:
    """Generate Kubeflow Pipelines (KFP) component YAML for Vertex AI Pipelines."""
    return """# Auto-generated by XLAxiom for Vertex AI Pipelines
name: xlaxiom_compiler_verification
description: Runs automated JAX and OpenXLA differential compiler verification on Vertex AI.
inputs:
  - {name: case_gcs_uri, type: String, description: 'GCS path to candidate case artifact'}
  - {name: accelerator_type, type: String, default: 'TPU_V5E', description: 'GCP accelerator type'}
outputs:
  - {name: verdict_json, type: String, description: 'Forensic reproduction verdict JSON'}
  - {name: report_html, type: HTML, description: 'Self-contained visual report with SVG DAG'}
implementation:
  container:
    image: us-docker.pkg.dev/google-cloud/xlaxiom/runner:latest
    command: [
      python, -m, xlaxiom.cli,
      reproduce,
      --case, {inputValue: case_gcs_uri},
      --strict
    ]
"""
