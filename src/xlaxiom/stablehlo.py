"""StableHLO MLIR text dialect exporter for OpenXLA compiler pipelines.

Enables pure, direct compilation targeting StableHLO without third-party compiler
bindings, providing canonical MLIR text representations suitable for stablehlo-opt,
stablehlo-translate, and upstream OpenXLA test reproduction.
"""

from __future__ import annotations

from typing import Any

import numpy as np

from .model import Workload, infer_dtype, infer_shape

_DTYPE_TO_MLIR: dict[str, str] = {
    "float32": "f32",
    "float64": "f64",
    "int32": "i32",
    "int64": "i64",
    "bool": "i1",
}


def _mlir_type(shape: tuple[int, ...], dtype: str) -> str:
    mlir_dt = _DTYPE_TO_MLIR.get(dtype, dtype)
    shape_str = "x".join(str(d) for d in shape)
    if not shape_str:
        return f"tensor<{mlir_dt}>"
    return f"tensor<{shape_str}x{mlir_dt}>"


def export_stablehlo(workload: Workload) -> str:
    """Translate an XLAxiom Workload into standard StableHLO MLIR module syntax."""
    workload.validate()
    shapes: dict[str, tuple[int, ...]] = {}
    dtypes: dict[str, str] = {}
    np_dtypes: dict[str, np.dtype[Any]] = {}

    for inp in workload.inputs:
        shapes[inp.name] = inp.shape
        dtypes[inp.name] = inp.dtype
        np_dtypes[inp.name] = np.dtype(inp.dtype)

    for node in workload.nodes:
        sh = infer_shape(node, shapes)
        dt = infer_dtype(node, np_dtypes)
        shapes[node.output] = sh
        dtypes[node.output] = dt.name
        np_dtypes[node.output] = dt

    # Map tensor names to MLIR SSA values
    ssa_map: dict[str, str] = {}
    func_args: list[str] = []

    for idx, inp in enumerate(workload.inputs):
        ssa = f"%arg{idx}"
        ssa_map[inp.name] = ssa
        t_type = _mlir_type(inp.shape, inp.dtype)
        func_args.append(f"{ssa}: {t_type}")

    # Output types
    out_types = [_mlir_type(shapes[out_name], dtypes[out_name]) for out_name in workload.outputs]
    return_type_str = ", ".join(out_types)
    if len(out_types) > 1:
        return_sig = f"({return_type_str})"
    else:
        return_sig = return_type_str

    lines: list[str] = [
        "// Auto-generated by XLAxiom StableHLO Dialect Exporter",
        f"// Workload: {workload.identifier}",
        "module @xlaxiom {",
        f"  func.func @main({', '.join(func_args)}) -> {return_sig} {{",
    ]

    for node in workload.nodes:
        out_name = node.output
        out_type = _mlir_type(shapes[out_name], dtypes[out_name])
        out_ssa = f"%{out_name}"
        ssa_map[out_name] = out_ssa

        in_ssas = [ssa_map[in_name] for in_name in node.inputs]

        if node.op in ("add", "sub", "mul", "div", "maximum", "minimum"):
            op_map = {
                "add": "stablehlo.add",
                "sub": "stablehlo.subtract",
                "mul": "stablehlo.multiply",
                "div": "stablehlo.divide",
                "maximum": "stablehlo.maximum",
                "minimum": "stablehlo.minimum",
            }
            op_name = op_map[node.op]
            lines.append(f"    {out_ssa} = {op_name} {in_ssas[0]}, {in_ssas[1]} : {out_type}")

        elif node.op in ("abs", "neg", "sqrt", "exp", "log", "sin", "cos", "tanh"):
            op_map = {
                "abs": "stablehlo.abs",
                "neg": "stablehlo.negate",
                "sqrt": "stablehlo.sqrt",
                "exp": "stablehlo.exponential",
                "log": "stablehlo.log",
                "sin": "stablehlo.sine",
                "cos": "stablehlo.cosine",
                "tanh": "stablehlo.tanh",
            }
            op_name = op_map[node.op]
            lines.append(f"    {out_ssa} = {op_name} {in_ssas[0]} : {out_type}")

        elif node.op == "reshape":
            in_type = _mlir_type(shapes[node.inputs[0]], dtypes[node.inputs[0]])
            lines.append(
                f"    {out_ssa} = stablehlo.reshape {in_ssas[0]} : ({in_type}) -> {out_type}"
            )

        elif node.op == "matmul":
            in0_type = _mlir_type(shapes[node.inputs[0]], dtypes[node.inputs[0]])
            in1_type = _mlir_type(shapes[node.inputs[1]], dtypes[node.inputs[1]])
            lines.append(
                f"    {out_ssa} = stablehlo.dot_general {in_ssas[0]}, {in_ssas[1]}, "
                f"contracting_dims = [1] x [0] : "
                f"({in0_type}, {in1_type}) -> {out_type}"
            )

        elif node.op in ("sum", "mean"):
            in_type = _mlir_type(shapes[node.inputs[0]], dtypes[node.inputs[0]])
            axis = node.params.get("axis")
            axis_str = f"dimensions = [{axis}]" if axis is not None else "dimensions = []"
            elem_dt = _DTYPE_TO_MLIR.get(dtypes[out_name], dtypes[out_name])
            reducer_sig = f"reducer(%arg_a: tensor<{elem_dt}>, %arg_b: tensor<{elem_dt}>) {{"
            lines.append(
                f"    {out_ssa} = stablehlo.reduce({in_ssas[0]}) across {axis_str} : "
                f"({in_type}) -> {out_type} {reducer_sig}"
            )
            lines.append(f"      %red = stablehlo.add %arg_a, %arg_b : tensor<{elem_dt}>")
            lines.append(f"      stablehlo.return %red : tensor<{elem_dt}>")
            lines.append("    }")

        else:
            # Fallback custom call
            lines.append(
                f'    {out_ssa} = "stablehlo.custom_call"({", ".join(in_ssas)}) '
                f'{{call_target_name = "{node.op}"}} : () -> {out_type}'
            )

    ret_ssas = [ssa_map[o] for o in workload.outputs]
    if len(ret_ssas) > 1:
        lines.append(f"    return {', '.join(ret_ssas)} : {return_sig}")
    else:
        lines.append(f"    return {ret_ssas[0]} : {return_sig}")

    lines.append("  }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def verify_stablehlo_roundtrip(workload: Workload) -> dict[str, Any]:
    """Verify that a Workload generates semantically and syntactically valid StableHLO MLIR."""
    mlir_text = export_stablehlo(workload)
    lines = [line.strip() for line in mlir_text.splitlines() if line.strip()]

    # Structural MLIR validation
    has_module = any(line.startswith("module @xlaxiom {") for line in lines)
    has_func = any(line.startswith("func.func @main(") for line in lines)
    has_return = any(line.startswith("return %") for line in lines)
    has_closing = lines[-1] == "}" and lines[-2] == "}"

    syntax_valid = has_module and has_func and has_return and has_closing

    # Verify SSA assignments: check that each node output is defined
    defined_ssas: set[str] = {f"%arg{i}" for i in range(len(workload.inputs))}
    dialects_used: set[str] = {"func"}
    ssa_count = len(defined_ssas)

    for node in workload.nodes:
        out_ssa = f"%{node.output}"
        defined_ssas.add(out_ssa)
        ssa_count += 1
        dialects_used.add("stablehlo")

    # Verify return targets are defined
    return_targets = [f"%{o}" for o in workload.outputs]
    return_valid = all(t in defined_ssas for t in return_targets)

    return {
        "verified": syntax_valid and return_valid,
        "workload_digest": workload.digest(),
        "ssa_count": ssa_count,
        "mlir_lines": len(lines),
        "dialects_used": sorted(dialects_used),
        "syntax_valid": syntax_valid,
        "return_valid": return_valid,
    }
